export const getLocationsByType = (type: Location['type']) =>
  locations.filter((l) => l.type === type);

export const getChildLocations = (parentId: string) =>
  locations.filter((l) => l.parentId === parentId);

export const getLocationById = (id: string) =>
  locations.find((l) => l.id === id);

export const getLocationPath = (id: string): Location[] => {
  const path: Location[] = [];
  let current = getLocationById(id);
  while (current) {
    path.unshift(current);
    current = current.parentId ? getLocationById(current.parentId) : undefined;
  }
  return path;
};

export const defaultLocation = locations.find((l) => l.id === 'kanakapura')!;
